<?php

declare(strict_types=1);

namespace KaririCode\Devkit\Configuration;

use KaririCode\Devkit\Contract\ConfigGenerator;
use KaririCode\Devkit\Core\ProjectContext;
use Override;

use const PHP_EOL;

/**
 * Generates `.kcode/docker/compose.yaml` — the per-project container runtime.
 *
 * Replaces the per-component `docker-compose.yml`, `.env.example` and the
 * Docker targets of the legacy Makefile. Key properties:
 *
 *   - The project is mounted at its host path, so every absolute path kcode
 *     computes (configs, `.kcode/vendor/bin/`, build output) is valid inside
 *     the container without translation.
 *   - The `php` service idles (`sleep infinity`); kcode runs tools with
 *     `docker compose exec`, as the host user.
 *   - The built image is tagged by PHP version plus a hash of the Dockerfile,
 *     so components with identical settings reuse one image.
 *
 * @since 1.2.0
 */
final readonly class DockerComposeGenerator implements ConfigGenerator
{
    public const string SERVICE = 'php';
    public const string PHP_INI_TARGET = '/usr/local/etc/php/conf.d/zz-kcode.ini';

    /** @var array<string, string> */
    private const array BASE_ENVIRONMENT = [
        'HOME' => '/tmp',
        'COMPOSER_HOME' => '/tmp/composer',
        'COMPOSER_CACHE_DIR' => '/tmp/composer/cache',
        'KCODE_CONTAINER' => '1',
        // The bind mount is owned by the host user; let git (used by Composer) trust it.
        'GIT_CONFIG_COUNT' => '1',
        'GIT_CONFIG_KEY_0' => 'safe.directory',
        'GIT_CONFIG_VALUE_0' => '*',
    ];

    public function __construct(
        private DockerfileGenerator $dockerfile = new DockerfileGenerator(),
        private YamlWriter $yaml = new YamlWriter(),
    ) {
    }

    /** Compose project name: "kcode-" followed by the slugged package name. */
    public static function projectName(ProjectContext $context): string
    {
        $slug = trim((string) preg_replace('/[^a-z0-9]+/', '-', strtolower($context->projectName)), '-');

        return 'kcode-' . ('' !== $slug ? $slug : 'project');
    }

    #[Override]
    public function toolName(): string
    {
        return 'docker-compose';
    }

    #[Override]
    public function outputPath(): string
    {
        return 'docker/compose.yaml';
    }

    #[Override]
    public function generate(ProjectContext $context): string
    {
        $services = [self::SERVICE => $this->phpService($context)];

        foreach ($context->docker->services as $name => $definition) {
            $services[$name] = \is_string($definition) ? ['image' => $definition] : $definition;
        }

        $header = implode(PHP_EOL, [
            '# Generated by KaririCode Devkit — customize via devkit.php → docker (regenerated by kcode init).',
            '# Manage with: kcode up | kcode down | kcode shell | kcode exec <command> | kcode ps | kcode logs',
        ]);

        return $header . PHP_EOL . $this->yaml->dump([
            'name' => self::projectName($context),
            'services' => $services,
        ]);
    }

    /** Local tag of the generated image, shared by projects with an identical Dockerfile. */
    public function imageTag(ProjectContext $context): string
    {
        $fingerprint = substr(sha1($this->dockerfile->generate($context)), 0, 12);

        return "kcode-php:{$context->docker->phpVersion}-{$fingerprint}";
    }

    /** @return array<string, mixed> */
    private function phpService(ProjectContext $context): array
    {
        $docker = $context->docker;
        $root = $context->projectRoot;

        $service = $docker->buildsImage()
            ? [
                'image' => $this->imageTag($context),
                'build' => ['context' => '.', 'dockerfile' => 'Dockerfile'],
                // Build only when the tag is missing; a Dockerfile change yields a new tag.
                'pull_policy' => 'missing',
            ]
            : ['image' => $docker->image];

        $service += [
            'init' => true,
            'command' => ['sleep', 'infinity'],
            'working_dir' => $root,
            'environment' => array_replace(self::BASE_ENVIRONMENT, $docker->environment),
            'volumes' => ["{$root}:{$root}", './php.ini:' . self::PHP_INI_TARGET . ':ro'],
            'extra_hosts' => ['host.docker.internal:host-gateway'],
        ];

        if ([] !== $docker->ports) {
            $service['ports'] = $docker->ports;
        }

        if ([] !== $docker->services) {
            $service['depends_on'] = array_keys($docker->services);
        }

        return $this->merge($service, $docker->service);
    }

    /**
     * Merge raw Compose keys from devkit.php: maps merge, lists append, scalars replace.
     *
     * @param array<string, mixed> $service
     * @param array<string, mixed> $overrides
     * @return array<string, mixed>
     */
    private function merge(array $service, array $overrides): array
    {
        foreach ($overrides as $key => $value) {
            $current = $service[$key] ?? null;

            $service[$key] = match (true) {
                \is_array($current) && \is_array($value) && array_is_list($current) && array_is_list($value)
                    => array_values(array_unique([...$current, ...$value], \SORT_REGULAR)),
                \is_array($current) && \is_array($value) => array_replace($current, $value),
                default => $value,
            };
        }

        return $service;
    }
}
