<?php

declare(strict_types=1);

namespace KaririCode\Devkit\Configuration;

use KaririCode\Devkit\Contract\ConfigGenerator;
use KaririCode\Devkit\Core\ProjectContext;
use Override;

use const PHP_EOL;

/**
 * Generates `.kcode/docker/php.ini`, bind-mounted into the PHP container.
 *
 * Replaces the per-component `.docker/php/kariricode-php.ini`. Xdebug is
 * installed but off by default; `XDEBUG_MODE=debug kcode test --docker`
 * turns it on for one run, because kcode forwards XDEBUG_* variables.
 *
 * @since 1.2.0
 */
final class PhpIniGenerator implements ConfigGenerator
{
    /** @var array<string, string> */
    private const array DEFAULT_DIRECTIVES = [
        'memory_limit' => '-1',
        'date.timezone' => 'UTC',
        'display_errors' => 'On',
        'error_reporting' => 'E_ALL',
        'xdebug.mode' => 'off',
        'xdebug.start_with_request' => 'trigger',
        'xdebug.client_host' => 'host.docker.internal',
        'xdebug.client_port' => '9003',
    ];

    #[Override]
    public function toolName(): string
    {
        return 'php-ini';
    }

    #[Override]
    public function outputPath(): string
    {
        return 'docker/php.ini';
    }

    #[Override]
    public function generate(ProjectContext $context): string
    {
        $directives = array_replace(self::DEFAULT_DIRECTIVES, $context->docker->ini);
        $lines = ['; Generated by KaririCode Devkit — customize via devkit.php → docker.ini (regenerated by kcode init).'];

        foreach ($directives as $name => $value) {
            $lines[] = "{$name} = {$this->formatValue($value)}";
        }

        return implode(PHP_EOL, $lines) . PHP_EOL;
    }

    /**
     * Quote values the INI parser would otherwise cut short (";" starts a comment).
     * Bare values stay bare so constant expressions such as "E_ALL & ~E_DEPRECATED" still evaluate.
     */
    private function formatValue(string $value): string
    {
        if ('' === $value || 1 === preg_match('/[;="]|^\s|\s$/', $value)) {
            return '"' . str_replace('"', '', $value) . '"';
        }

        return $value;
    }
}
