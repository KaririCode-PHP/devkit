<?php

declare(strict_types=1);

namespace KaririCode\Devkit\Configuration;

use KaririCode\Devkit\Contract\ConfigGenerator;
use KaririCode\Devkit\Core\ProjectContext;
use Override;

use const PHP_EOL;

/**
 * Generates `.kcode/docker/Dockerfile` — the shared PHP CLI image.
 *
 * Replaces the per-component `.docker/php/Dockerfile`. The image carries
 * PHP, the configured extensions (installed by install-php-extensions,
 * which resolves build dependencies per extension), Composer and git.
 * php.ini is bind-mounted at runtime instead of baked in, so components
 * with the same PHP version and extensions share one image.
 *
 * @since 1.2.0
 */
final class DockerfileGenerator implements ConfigGenerator
{
    private const string EXTENSION_INSTALLER = 'mlocati/php-extension-installer:2';
    private const string COMPOSER_IMAGE = 'composer:2';
    private const array BASE_PACKAGES = ['git', 'unzip'];

    #[Override]
    public function toolName(): string
    {
        return 'dockerfile';
    }

    #[Override]
    public function outputPath(): string
    {
        return 'docker/Dockerfile';
    }

    #[Override]
    public function generate(ProjectContext $context): string
    {
        $docker = $context->docker;
        $packages = implode(' ', array_values(array_unique([...self::BASE_PACKAGES, ...$docker->packages])));

        $lines = [
            '# Generated by KaririCode Devkit — customize via devkit.php → docker (regenerated by kcode init).',
            "FROM php:{$docker->phpVersion}-cli-alpine",
            '',
        ];

        if ([] !== $docker->extensions) {
            $extensions = implode(' ', $docker->extensions);
            $lines[] = '# install-php-extensions resolves and removes build dependencies per extension.';
            $lines[] = 'COPY --from=' . self::EXTENSION_INSTALLER . ' /usr/bin/install-php-extensions /usr/local/bin/';
            $lines[] = "RUN install-php-extensions {$extensions}";
            $lines[] = '';
        }

        $lines[] = 'COPY --from=' . self::COMPOSER_IMAGE . ' /usr/bin/composer /usr/local/bin/composer';
        $lines[] = "RUN apk add --no-cache {$packages}";
        $lines[] = '';
        $lines[] = '# Any host UID runs kcode tools: HOME and Composer state live in /tmp.';
        $lines[] = 'ENV HOME=/tmp COMPOSER_HOME=/tmp/composer COMPOSER_CACHE_DIR=/tmp/composer/cache';

        return implode(PHP_EOL, $lines) . PHP_EOL;
    }
}
