<?php

declare(strict_types=1);

namespace KaririCode\Devkit\Core;

use const DIRECTORY_SEPARATOR;
use const FILE_APPEND;

use FilesystemIterator;
use KaririCode\Devkit\Contract\ConfigGenerator;
use KaririCode\Devkit\Contract\ToolRunner;
use KaririCode\Devkit\Exception\DevkitException;
use KaririCode\Devkit\ValueObject\QualityReport;
use KaririCode\Devkit\ValueObject\ToolResult;

use const PHP_EOL;

use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use SplFileInfo;

/**
 * Top-level orchestrator for all devkit operations.
 *
 * Wired in `bin/kcode`. Holds config generators, tool runners,
 * and the project context. Every public method is a high-level
 * operation exposed through the CLI.
 *
 * @since 1.0.0
 */
final class Devkit
{
    private const string VERSION = '1.0.0';

    private ?ProjectContext $context = null;
    private ?ProcessExecutor $executor = null;

    /** @var array<string, ConfigGenerator> */
    private array $generators = [];

    /** @var array<string, ToolRunner> */
    private array $runners = [];

    public function __construct(
        private readonly ProjectDetector $detector,
        private readonly ComposerResolver $composerResolver = new ComposerResolver(),
        private readonly ProjectLocator $locator = new ProjectLocator(),
    ) {
    }

    public static function version(): string
    {
        return self::VERSION;
    }

    // ── Registration ──────────────────────────────────────────────

    public function addGenerator(ConfigGenerator $generator): void
    {
        $this->generators[$generator->toolName()] = $generator;
    }

    public function addRunner(ToolRunner $runner): void
    {
        $this->runners[$runner->toolName()] = $runner;
    }

    // ── Context ───────────────────────────────────────────────────

    /**
     * Detect the project context once and cache it.
     *
     * The project root is the nearest ancestor of `$workingDirectory` (default:
     * the current directory) that contains `composer.json`, so a global `kcode`
     * works from any subdirectory of a project.
     */
    public function context(?string $workingDirectory = null): ProjectContext
    {
        return $this->context ??= $this->detector->detect(
            $this->locator->locate($workingDirectory ?? (getcwd() ?: '.')),
        );
    }

    // ── Init ──────────────────────────────────────────────────────

    /** Generate all config files inside `.kcode/`. Returns file count. */
    public function init(?string $workingDirectory = null): int
    {
        $context = $this->context($workingDirectory);
        $this->ensureDirectories($context);

        $count = 0;

        foreach ($this->generators as $generator) {
            $path = $context->configPath($generator->outputPath());

            $directoryPath = \dirname($path);
            if (! is_dir($directoryPath)) {
                mkdir($directoryPath, 0o755, true);
            }

            file_put_contents($path, $generator->generate($context));
            ++$count;
        }

        $this->appendGitIgnore($context);

        return $count;
    }

    /**
     * Install dev tools into `.kcode/vendor/` by running Composer.
     *
     * Reads the `.kcode/composer.json` manifest generated by `KcodeComposerGenerator`
     * and runs `composer install --working-dir=.kcode/` so tools are available
     * at `.kcode/vendor/bin/` for Tier-1 binary resolution. In container mode
     * Composer runs inside the PHP container, so platform checks match the
     * PHP that will execute the tools.
     *
     * Output streams live to the user's terminal.
     *
     * @return int Composer exit code (0 = success)
     *
     * @since 1.0.0
     */
    public function installTools(?string $workingDirectory = null): int
    {
        $context = $this->context($workingDirectory);

        if (! is_file($context->configPath('composer.json'))) {
            // KcodeComposerGenerator not registered — nothing to install
            return 0;
        }

        $executor = $this->executor();
        $containerExitCode = $executor->ensureContainer();

        if (0 !== $containerExitCode) {
            return $containerExitCode;
        }

        return $executor->passthru([
            $this->composerBinary(),
            'install',
            '--working-dir=' . $context->devkitDir,
            '--no-interaction',
            '--prefer-dist',
            '--optimize-autoloader',
            '--no-scripts',
        ]);
    }

    // ── Execution environment ─────────────────────────────────────

    /**
     * Replace the process executor (bin/kcode injects one bound to the
     * project root, optionally containerized by `--docker`).
     *
     * @since 1.2.0
     */
    public function useExecutor(ProcessExecutor $executor): void
    {
        $this->executor = $executor;
    }

    /** @since 1.2.0 */
    public function executor(): ProcessExecutor
    {
        return $this->executor ??= new ProcessExecutor($this->context()->projectRoot);
    }

    /** @since 1.2.0 */
    public function container(): ContainerRuntime
    {
        return new ContainerRuntime($this->context());
    }

    /**
     * Prepare the execution environment before a tool command runs.
     *
     * @return int 0 when ready, a non-zero exit code otherwise
     *
     * @since 1.2.0
     */
    public function prepareToolchain(): int
    {
        return $this->prepareContainer();
    }

    /**
     * In container mode, generate `.kcode/docker/` when missing and start the
     * PHP container when it is not running. No-op in host mode.
     *
     * @return int 0 when ready, a non-zero exit code otherwise
     *
     * @since 1.2.0
     */
    public function prepareContainer(): int
    {
        $executor = $this->executor();

        if (! $executor->isContainerized()) {
            return 0;
        }

        if (! $this->container()->isConfigured()) {
            $this->init();
        }

        return $executor->ensureContainer();
    }

    // ── Run ───────────────────────────────────────────────────────

    /** @param list<string> $arguments */
    public function run(string $toolName, array $arguments = []): ToolResult
    {
        $runner = $this->runners[$toolName] ?? null;

        if (null === $runner) {
            throw new DevkitException(\sprintf(
                'Unknown tool "%s". Available: %s',
                $toolName,
                implode(', ', array_keys($this->runners)),
            ));
        }

        return $runner->run($arguments);
    }

    /** Check if a tool runner is registered and its binary is available. */
    public function isToolAvailable(string $toolName): bool
    {
        return isset($this->runners[$toolName]) && $this->runners[$toolName]->isAvailable();
    }

    // ── Quality Pipeline ──────────────────────────────────────────

    /**
     * Full quality pipeline: cs-check → analyse → test.
     *
     * Skips unavailable tools instead of failing.
     *
     * @param list<string> $onlyTools Restrict to these tools (empty = all).
     */
    public function quality(array $onlyTools = []): QualityReport
    {
        $pipeline = [] !== $onlyTools
            ? $onlyTools
            : ['cs-fixer', 'phpstan', 'psalm', 'phpunit'];

        $results = [];

        foreach ($pipeline as $tool) {
            if (! $this->isToolAvailable($tool)) {
                continue;
            }

            $extraArgs = match ($tool) {
                'cs-fixer' => ['--dry-run', '--diff'],
                'rector' => ['--dry-run'],
                default => [],
            };

            $results[] = $this->run($tool, $extraArgs);
        }

        return new QualityReport($results);
    }

    // ── Clean ─────────────────────────────────────────────────────

    public function clean(?string $workingDirectory = null): void
    {
        $buildDir = $this->context($workingDirectory)->buildDir;

        if (is_dir($buildDir)) {
            $this->removeRecursive($buildDir);
        }

        mkdir($buildDir, 0o755, true);
    }

    /** @return list<string> */
    public function registeredTools(): array
    {
        return array_keys($this->runners);
    }

    // ── Internals ─────────────────────────────────────────────────

    /** Composer inside the container is on PATH; on the host it is resolved. */
    private function composerBinary(): string
    {
        return $this->executor()->isContainerized() ? 'composer' : $this->composerResolver->resolve();
    }

    private function ensureDirectories(ProjectContext $context): void
    {
        foreach ([$context->devkitDir, $context->buildDir] as $directoryPath) {
            if (! is_dir($directoryPath) && ! mkdir($directoryPath, 0o755, true)) {
                throw DevkitException::directoryNotWritable($directoryPath);
            }
        }
    }

    private function appendGitIgnore(ProjectContext $context): void
    {
        $gitignore = $context->projectRoot . DIRECTORY_SEPARATOR . '.gitignore';
        $entry = '.kcode/';

        // Create .gitignore if it doesn't exist
        if (! is_file($gitignore)) {
            file_put_contents(
                $gitignore,
                '# KaririCode Devkit — generated configs and build artifacts' . PHP_EOL
                . $entry . PHP_EOL,
            );

            return;
        }

        $content = file_get_contents($gitignore);

        if (false === $content) {
            return;
        }

        // Already covered
        if (str_contains($content, $entry)) {
            return;
        }

        // Migrate: if old .kcode/build/ entry exists, replace with .kcode/
        $legacyEntry = '.kcode/build/';
        if (str_contains($content, $legacyEntry)) {
            $content = str_replace($legacyEntry, $entry, $content);
            file_put_contents($gitignore, $content);

            return;
        }

        file_put_contents(
            $gitignore,
            PHP_EOL . '# KaririCode Devkit — generated configs and build artifacts' . PHP_EOL
            . $entry . PHP_EOL,
            FILE_APPEND,
        );
    }

    private function removeRecursive(string $directoryPath): void
    {
        $items = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($directoryPath, FilesystemIterator::SKIP_DOTS),
            RecursiveIteratorIterator::CHILD_FIRST,
        );

        foreach ($items as $item) {
            /** @var SplFileInfo $item */
            $item->isDir() ? rmdir($item->getPathname()) : unlink($item->getPathname());
        }

        rmdir($directoryPath);
    }
}
